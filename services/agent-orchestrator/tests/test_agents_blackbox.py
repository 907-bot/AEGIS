from agents.competitive import CompetitiveCartographer

TEST_URL = "https://stripe.com"
INV_ID = "bb-test-agents-01"


@pytest.fixture(scope="module")
def llm_router():
    return LLMRouter()


class TestSpecializedAgentsDataValidation:
    """Validate data output generated by each of the 7 AI agents."""

    @pytest.mark.asyncio
    async def test_tech_stack_agent_data_generation(self, llm_router):
        agent = TechStackAgent(llm_router)
        result = await agent.investigate(f"{INV_ID}-tech", TEST_URL)

        # 1. Status and latency assertions
        assert result.get("status") == "completed", f"Agent failed: {result.get('error')}"
        assert result.get("agent_type") == "tech_stack"
        assert isinstance(result.get("confidence"), float)
        assert 0.0 <= result["confidence"] <= 1.0
        assert result.get("latency_ms", 0) >= 0

        # 2. Data payload assertions
        data = result.get("data", {})
        assert isinstance(data, dict), "Agent data must be a dictionary"
        assert len(data) > 0, "Agent data must not be empty"

        # Check required schema fields
        for field in ["frontend", "infrastructure", "databases_inferred", "tech_maturity", "innovation_score"]:
            assert field in data, f"Missing field '{field}' in tech_stack output"

        # Check types
        assert isinstance(data["frontend"], list)
        assert isinstance(data["infrastructure"], list)
        assert isinstance(data["databases_inferred"], list)

        # Check bounds
        inv_score = data["innovation_score"]
        assert isinstance(inv_score, (int, float))
        assert 0 <= inv_score <= 100, f"Innovation score {inv_score} out of bounds [0, 100]"

    @pytest.mark.asyncio
    async def test_sentry_agent_data_generation(self, llm_router):
        agent = SentryAgent(llm_router)
        result = await agent.investigate(f"{INV_ID}-sentry", TEST_URL)

        assert result.get("status") == "completed", f"Agent failed: {result.get('error')}"
        assert result.get("agent_type") == "sentry"
        assert 0.0 <= result.get("confidence", 0.0) <= 1.0

        data = result.get("data", {})
        assert isinstance(data, dict)
        assert "company_name" in data, "company_name must be extracted by Sentry"
        assert len(str(data["company_name"])) >= 2, "company_name must not be empty or single char"
        assert data["company_name"].lower() not in ["...", "todo", "unknown", "null"]

        assert "business_model" in data
        assert "tech_stack" in data
        assert isinstance(data["tech_stack"], dict)

        # Verify evidence trace
        evidence = result.get("evidence", [])
        assert isinstance(evidence, list)
        assert len(evidence) > 0, "Agent must return evidence citations"

