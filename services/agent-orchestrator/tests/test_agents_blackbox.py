"""
Black-Box Validation Suite for AEGIS 7 Specialized Reconnaissance Agents.
Validates data contracts, schema types, value ranges, anti-stub constraints, and evidence tracking.
"""
import pytest
import os
from dotenv import load_dotenv

# Ensure environment is loaded
load_dotenv(".env")
load_dotenv("../../.env")

from utils.llm_router import LLMRouter
from agents.sentry import SentryAgent
